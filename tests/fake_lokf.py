#!/usr/bin/env python3
"""A stand-in for the lokf toolkit's `adapt`, for the fast tests.

It takes the command the scaffold and the lokf-adapt recipe run
(`adapt SRC [flags] --lokf CORE -o OUT`, with `--dry-run` or `--check`), and
writes OUT as `lokf adapt` heads its copy: two comment lines naming the
source file, then the source with `lokf` added to its imports. Beyond that
SRC and CORE exist, it checks nothing the real toolkit checks. Nothing here
needs the network.

FAKE_LOKF_OLD=1 answers as lokf 0.8.0 does, which has no adapt command, and
FAKE_LOKF_FAIL=write fails a run that would write, so the scaffold's
refusal and its hand-off can be tested.
"""

import os
import sys
from pathlib import Path


def main(argv):
    if os.environ.get("FAKE_LOKF_OLD") == "1":
        print("Usage: lokf [OPTIONS] COMMAND [ARGS]...\nError: No such command 'adapt'.", file=sys.stderr)
        return 2
    if not argv or argv[0] != "adapt":
        print(f"fake lokf: only adapt is faked, not {argv[:1]}", file=sys.stderr)
        return 2
    args = argv[1:]
    src, core, out = Path(args[0]), Path(args[args.index("--lokf") + 1]), Path(args[args.index("-o") + 1])
    for path in (src, core):
        if not path.is_file():
            print(f"fake lokf: no such file: {path}", file=sys.stderr)
            return 1
    text = src.read_text(encoding="utf-8").replace("imports:\n  - linkml:types\n", "imports:\n  - linkml:types\n  - lokf\n", 1)
    copy = f"# Generated by `lokf adapt` from {src.name} ({src.stem}); do not edit.\n# Imports lokf: a domain schema lists this file beside it (SPEC 6.2).\n{text}"
    if "--dry-run" in args:
        print(f"{src} -> {out}\n  verified beside lokf.yaml (dry run, nothing written)")
        return 0
    if "--check" in args:
        current = out.is_file() and out.read_text(encoding="utf-8") == copy
        print(f"{out} is {'current' if current else 'stale'}")
        return 0 if current else 1
    if os.environ.get("FAKE_LOKF_FAIL") == "write":
        print("fake lokf: told to fail", file=sys.stderr)
        return 1
    out.write_text(copy, encoding="utf-8")
    print(f"{src} -> {out}\n  verified beside lokf.yaml")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
